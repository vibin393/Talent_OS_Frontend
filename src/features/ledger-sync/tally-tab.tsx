"use client";

import {
  Button,
  Caption1,
  Checkbox,
  createTableColumn,
  Dialog,
  DialogActions,
  DialogBody,
  DialogContent,
  DialogSurface,
  DialogTitle,
  Field,
  Input,
  makeStyles,
  type TableColumnDefinition,
  tokens,
} from "@fluentui/react-components";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useState } from "react";
import { useAppToast } from "@/components/toast";
import { AdminGrid } from "@/features/admin/admin-grid";
import { formatDateTime } from "@/features/admin/ui";
import { errorMessage } from "@/lib/api/errors";
import { newIdempotencyKey } from "@/features/receivables/logic";
import { downloadApiFile } from "@/lib/api/download";
import { type LedgerRunOut, ledgerApi, ledgerKeys } from "./api";

const useStyles = makeStyles({ root: { display: "flex", flexDirection: "column", gap: tokens.spacingVerticalM } });

/** The "Tally files" tab: generate a TallyPrime import file per period and download earlier runs. */
export function TallyTab({ legalEntityId, installationId }: { legalEntityId: string | null; installationId: string | null }) {
  const styles = useStyles();
  const toast = useAppToast();
  const qc = useQueryClient();
  const [open, setOpen] = useState(false);
  const q = useQuery({
    queryKey: ledgerKeys.runs(legalEntityId ?? undefined),
    queryFn: ({ signal }) => ledgerApi.runs(legalEntityId ?? undefined, "tally_file", signal),
  });

  const columns: TableColumnDefinition<LedgerRunOut>[] = [
    createTableColumn({ columnId: "period", renderHeaderCell: () => "Period", renderCell: (r) => `${r.from_date ?? ""} – ${r.to_date ?? ""}` }),
    createTableColumn({ columnId: "documents", renderHeaderCell: () => "Documents", renderCell: (r) => String(r.counts.documents ?? 0) }),
    createTableColumn({ columnId: "by", renderHeaderCell: () => "Generated by", renderCell: (r) => r.created_by_name ?? "—" }),
    createTableColumn({ columnId: "on", renderHeaderCell: () => "Generated on", renderCell: (r) => formatDateTime(r.created_at) }),
    createTableColumn({
      columnId: "download",
      renderHeaderCell: () => "Download",
      renderCell: (r) =>
        r.file_id ? (
          <Button size="small" onClick={() => void downloadApiFile(ledgerApi.runFileUrl(r.id), "tally-import.xml").catch((e) => toast.error(errorMessage(e)))}>
            Download
          </Button>
        ) : (
          "—"
        ),
    }),
  ];

  return (
    <div className={styles.root}>
      <div>
        <Button appearance="primary" disabled={!legalEntityId} onClick={() => setOpen(true)}>
          Generate Tally file
        </Button>
      </div>
      <AdminGrid items={q.data?.items} columns={columns} getRowId={(r) => r.id} loading={q.isPending} error={q.error} emptyText="No Tally files yet." label="Tally files" />
      <Caption1>Import the file in TallyPrime: Gateway of Tally → Import → Vouchers (or Masters).</Caption1>
      {open && legalEntityId ? (
        <GenerateDialog legalEntityId={legalEntityId} installationId={installationId} onClose={() => setOpen(false)} onDone={() => void qc.invalidateQueries({ queryKey: ledgerKeys.runs(legalEntityId) })} />
      ) : null}
    </div>
  );
}

function GenerateDialog({ legalEntityId, installationId, onClose, onDone }: { legalEntityId: string; installationId: string | null; onClose: () => void; onDone: () => void }) {
  const toast = useAppToast();
  const [from, setFrom] = useState("");
  const [to, setTo] = useState("");
  const [masters, setMasters] = useState(false);
  const [key] = useState(newIdempotencyKey);
  const m = useMutation({
    mutationFn: () =>
      ledgerApi.createRun({ kind: "tally_file", legal_entity_id: legalEntityId, installation_id: installationId ?? undefined, from_date: from, to_date: to, include_masters: masters }, key),
    onSuccess: () => {
      toast.success("Tally file generated.");
      onDone();
      onClose();
    },
    onError: (e) => toast.error(errorMessage(e)),
  });
  return (
    <Dialog open onOpenChange={(_, d) => (!d.open ? onClose() : undefined)}>
      <DialogSurface>
        <DialogBody>
          <DialogTitle>Generate Tally import file</DialogTitle>
          <DialogContent>
            <Field label="From" required>
              <Input type="date" value={from} onChange={(_, d) => setFrom(d.value)} />
            </Field>
            <Field label="To" required>
              <Input type="date" value={to} onChange={(_, d) => setTo(d.value)} />
            </Field>
            <Checkbox label="Include masters (customers and ledgers)" checked={masters} onChange={(_, d) => setMasters(Boolean(d.checked))} />
          </DialogContent>
          <DialogActions>
            <Button appearance="primary" disabled={!from || !to || m.isPending} onClick={() => m.mutate()}>
              Generate
            </Button>
            <Button onClick={onClose}>Cancel</Button>
          </DialogActions>
        </DialogBody>
      </DialogSurface>
    </Dialog>
  );
}
