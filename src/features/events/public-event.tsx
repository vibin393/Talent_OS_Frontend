"use client";

import { Body1, Button, Card, Checkbox, Field, Input, Link, Select, Spinner, Text } from "@fluentui/react-components";
import { useQuery } from "@tanstack/react-query";
import { useState } from "react";
import { publicCampusApi } from "@/features/campus/api";
import { isE164, isEmail, plainFieldKeys } from "@/features/campus/logic";
import { ErrorLive, Heading, NoticeBox, PublicShell, StateCard, usePublicStyles } from "@/features/campus/public/public-ui";
import type { PublicEventView } from "@/features/campus/types";
import { BotChallenge } from "@/features/careers/apply/bot-challenge";
import { linkErrorCopy } from "@/features/public-links/logic";
import { fieldErrors, isApiError } from "@/lib/api/errors";
import { KIND_LABELS } from "./logic";
import type { EventKind } from "./types";

function errorCopy(e: unknown) {
  return isApiError(e) ? linkErrorCopy(e.status, e.code) : linkErrorCopy(500, undefined);
}

function when(v: Pick<PublicEventView, "starts_at" | "ends_at" | "timezone">): string {
  try {
    const f = new Intl.DateTimeFormat(undefined, { dateStyle: "medium", timeStyle: "short", timeZone: v.timezone });
    const t = new Intl.DateTimeFormat(undefined, { timeStyle: "short", timeZone: v.timezone });
    return `${f.format(new Date(v.starts_at))} – ${t.format(new Date(v.ends_at))} (${v.timezone})`;
  } catch {
    return `${v.starts_at} – ${v.ends_at}`;
  }
}

/** The check-in QR (server-rendered SVG markup) shown on the pass. */
function QrPass({ svg, url, label }: { svg: string; url?: string | null; label: string }) {
  const styles = usePublicStyles();
  return (
    <>
      {/* The SVG is generated by our own API from the check-in URL (no user content). */}
      <div className={styles.qr} role="img" aria-label={label} dangerouslySetInnerHTML={{ __html: svg }} />
      {url && (
        <Text size={200} className={styles.muted} style={{ overflowWrap: "anywhere" }}>
          Can&apos;t scan? Show this link at the desk: <Link href={url}>{url}</Link>
        </Text>
      )}
    </>
  );
}

/** `/campus/e/[token]`: register for a recruitment event, or (personal link) show the check-in pass. */
export function PublicEventPage({ token }: { token: string }) {
  const styles = usePublicStyles();
  const view = useQuery({
    queryKey: ["public", "campus", "event", token],
    queryFn: ({ signal }) => publicCampusApi.event(token, signal),
    retry: (n, e) => n < 1 && (!isApiError(e) || e.status === 0 || e.status >= 500),
    refetchOnWindowFocus: false,
    staleTime: Infinity,
  });
  const [done, setDone] = useState<{ status: string; qr_svg?: string | null; checkin_url?: string | null } | null>(null);

  let content: React.ReactNode;
  if (view.isPending) {
    content = (
      <Card className={styles.card}>
        <Spinner label="Loading…" />
      </Card>
    );
  } else if (view.isError) {
    const copy = errorCopy(view.error);
    content = <StateCard tone="error" title={copy.title} body={copy.body} />;
  } else {
    const v = view.data;
    if (v.mode === "pass") {
      content = (
        <StateCard
          tone="success"
          title={v.candidate_first_name ? `${v.candidate_first_name}, here is your check-in pass` : "Your check-in pass"}
          body={`Show this QR code at the check-in desk of ${v.event_name}, ${when(v)}${v.venue ? ` at ${v.venue}` : ""}.`}
        >
          {v.qr_svg ? <QrPass svg={v.qr_svg} url={v.checkin_url} label={`Check-in QR code for ${v.event_name}`} /> : <Body1>Your pass is not available yet.</Body1>}
        </StateCard>
      );
    } else if (done) {
      content = (
        <StateCard
          tone="success"
          title={done.status === "registered" ? "You are registered" : "You were already registered"}
          body={`Save or screenshot this QR code and show it at the check-in desk of ${v.event_name}.`}
        >
          {done.qr_svg && <QrPass svg={done.qr_svg} url={done.checkin_url} label={`Check-in QR code for ${v.event_name}`} />}
        </StateCard>
      );
    } else if (v.status === "closed") {
      content = <StateCard tone="error" title="Registration is closed" body={`Registration for ${v.event_name} is no longer open.`} />;
    } else {
      content = <EventForm token={token} view={v} onDone={setDone} onStale={() => void view.refetch()} />;
    }
  }
  return <PublicShell tenant={view.data?.tenant_name}>{content}</PublicShell>;
}

function EventForm({
  token,
  view,
  onDone,
  onStale,
}: {
  token: string;
  view: PublicEventView;
  onDone: (d: { status: string; qr_svg?: string | null; checkin_url?: string | null }) => void;
  onStale: () => void;
}) {
  const styles = usePublicStyles();
  const [name, setName] = useState("");
  const [email, setEmail] = useState("");
  const [phone, setPhone] = useState("");
  const [demandId, setDemandId] = useState(view.demands.length === 1 ? view.demands[0].id : "");
  const [agreed, setAgreed] = useState(false);
  const [marketing, setMarketing] = useState(false);
  const [whatsapp, setWhatsapp] = useState(false);
  const [botToken, setBotToken] = useState<string | null>(null);
  const [challengeKey, setChallengeKey] = useState(0);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const kind = KIND_LABELS[view.kind as EventKind] ?? "Event";

  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    const found: Record<string, string> = {};
    if (!name.trim()) found.full_name = "Enter your full name.";
    if (!isEmail(email)) found.email = "Enter a valid email address.";
    if (phone.trim() && !isE164(phone)) found.phone = "Start with + and your country code, for example +919876543210.";
    if (whatsapp && !phone.trim()) found.phone = "Add your mobile number to get WhatsApp messages.";
    if (view.demands.length > 1 && !demandId) found.demand_id = "Choose the role you are interested in.";
    if (view.notice && !agreed) found.agreed = "Tick the box to confirm you agree to the notice.";
    setErrors(found);
    if (Object.keys(found).length) {
      setError("Please check the fields marked below.");
      return;
    }
    setBusy(true);
    setError(null);
    try {
      const out = await publicCampusApi.registerEvent(token, {
        full_name: name.trim(),
        email: email.trim(),
        phone: phone.replace(/[\s-]/g, "") || null,
        demand_id: demandId || null,
        notice_id: view.notice?.notice_id ?? null,
        agreed: view.notice ? agreed : true,
        marketing_opt_in: marketing,
        whatsapp_opt_in: whatsapp,
        bot_token: botToken,
      });
      onDone(out);
    } catch (err) {
      if (isApiError(err) && err.status === 422) {
        const fe = plainFieldKeys(fieldErrors(err));
        setErrors(fe);
        setError(Object.keys(fe).length ? "Please check the fields marked below." : err.message);
      } else if (isApiError(err) && err.code === "notice_outdated") {
        setAgreed(false);
        setError("The privacy notice was just updated. Please read it again and tick the box.");
        onStale();
      } else {
        const copy = errorCopy(err);
        setError(isApiError(err) && err.status === 409 ? err.message : `${copy.title}. ${copy.body}`);
        if (isApiError(err) && err.code === "challenge_failed") {
          setBotToken(null);
          setChallengeKey((k) => k + 1);
        }
      }
    } finally {
      setBusy(false);
    }
  };

  return (
    <Card className={styles.card}>
      <form className={styles.form} onSubmit={submit} noValidate>
        <Heading focusKey="event">{view.event_name}</Heading>
        <dl className={styles.facts}>
          <dt>What</dt>
          <dd>{kind}</dd>
          <dt>When</dt>
          <dd>{when(view)}</dd>
          {view.venue && (
            <>
              <dt>Where</dt>
              <dd>{view.venue}</dd>
            </>
          )}
          {view.video_link && (
            <>
              <dt>Online</dt>
              <dd>
                <Link href={view.video_link} target="_blank" rel="noopener noreferrer">
                  Join link
                </Link>
              </dd>
            </>
          )}
        </dl>
        <Body1>Register to get your check-in QR code. Fields marked with an asterisk (*) are required.</Body1>
        <Field label="Full name" required validationState={errors.full_name ? "error" : "none"} validationMessage={errors.full_name}>
          <Input className={styles.input} value={name} maxLength={200} autoComplete="name" disabled={busy} onChange={(_, d) => setName(d.value)} />
        </Field>
        <Field label="Email" required validationState={errors.email ? "error" : "none"} validationMessage={errors.email}>
          <Input className={styles.input} type="email" value={email} maxLength={320} autoComplete="email" disabled={busy} onChange={(_, d) => setEmail(d.value)} />
        </Field>
        <Field label="Mobile number" hint="With country code, for example +91 98765 43210" validationState={errors.phone ? "error" : "none"} validationMessage={errors.phone}>
          <Input className={styles.input} type="tel" value={phone} maxLength={40} autoComplete="tel" disabled={busy} onChange={(_, d) => setPhone(d.value)} />
        </Field>
        {view.demands.length > 0 && (
          <Field label="Role you are interested in" required={view.demands.length > 1} validationState={errors.demand_id ? "error" : "none"} validationMessage={errors.demand_id}>
            <Select className={styles.input} value={demandId} disabled={busy} onChange={(_, d) => setDemandId(d.value)}>
              <option value="">{view.demands.length > 1 ? "Choose…" : "Any role"}</option>
              {view.demands.map((d) => (
                <option key={d.id} value={d.id}>
                  {d.title}
                </option>
              ))}
            </Select>
          </Field>
        )}
        {view.notice && (
          <>
            <NoticeBox notice={view.notice} />
            <Field validationState={errors.agreed ? "error" : "none"} validationMessage={errors.agreed}>
              <Checkbox
                className={styles.checkbox}
                required
                label="I have read the notice and agree to my details being used for this event *"
                checked={agreed}
                disabled={busy}
                onChange={(_, d) => setAgreed(Boolean(d.checked))}
              />
            </Field>
          </>
        )}
        {view.whatsapp_opt_in && (
          <Checkbox
            className={styles.checkbox}
            label="Optional: message me on WhatsApp when it is my turn"
            checked={whatsapp}
            disabled={busy}
            onChange={(_, d) => setWhatsapp(Boolean(d.checked))}
          />
        )}
        {view.marketing_notice && (
          <>
            <NoticeBox notice={view.marketing_notice} />
            <Checkbox
              className={styles.checkbox}
              label="Optional: keep me informed about future opportunities"
              checked={marketing}
              disabled={busy}
              onChange={(_, d) => setMarketing(Boolean(d.checked))}
            />
          </>
        )}
        {view.challenge && <BotChallenge key={challengeKey} provider={view.challenge.provider} siteKey={view.challenge.site_key} onToken={setBotToken} />}
        <ErrorLive message={error} />
        <div className={styles.actions}>
          <Button appearance="primary" size="large" type="submit" disabled={busy}>
            {busy ? <Spinner size="tiny" label="Registering…" /> : "Register"}
          </Button>
        </div>
      </form>
    </Card>
  );
}
